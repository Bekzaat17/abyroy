const pagesByLang: Record<Lang, AnswerPageContent[]> = { ru: ruPages, kk: kkPages };

export function getAnswerPages(lang: Lang) {
  return pagesByLang[lang];
}

export function getAnswerPage(lang: Lang, slug: string) {
  return pagesByLang[lang].find((page) => page.slug === slug);
}

export function getAnswerPageByKey(lang: Lang, key: AnswerKey) {
  return pagesByLang[lang].find((page) => page.key === key)!;
}

export function getAnswerPagesForService(lang: Lang, serviceKey: ServiceKey) {
  return pagesByLang[lang].filter((page) => page.serviceKey === serviceKey);
}

export function getAnswerHref(lang: Lang, page: AnswerPageContent) {
  const prefix = lang === "ru" ? "/ru" : "";
  return `${prefix}/answers/${page.slug}/`;
}
